/* global console, process */
// Writes the test vectors the Android port of encrypted public links is checked against, made with the
// shared TypeScript implementation (packages/api-client/src/e2ee.ts, docs/specs/public-folder-links.md).
// Every random value is fixed, so a Kotlin seal must match byte for byte.
// Run from the repository root: npx tsx apps/android/e2ee-link-vectors.ts
import { createHash, webcrypto } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import {
  FileCipher,
  accountKeys,
  b64url,
  encryptedSize,
  linkKeys,
  linkUrl,
  openLinkFile,
  unwrapLinkName,
  unwrapLinkSecret,
  wrapLinkFileKey,
  wrapLinkName,
  wrapLinkSecret,
} from '../../packages/api-client/src/e2ee';

const out = resolve(
  dirname(fileURLToPath(import.meta.url)),
  'app/src/test/resources/e2ee-link-vectors.json',
);
const hex = (b: Uint8Array) => Buffer.from(b).toString('hex');
/** Fixed bytes: a counter run through SHA-256, so each value is distinct and reproducible. */
const fixed = (label: string, n: number) => {
  const result = new Uint8Array(n);
  for (let i = 0, at = 0; at < n; i++) {
    const block = createHash('sha256').update(`${label}#${i}`).digest();
    result.set(block.subarray(0, Math.min(32, n - at)), at);
    at += 32;
  }
  return result;
};
// The next values random() hands out; anything unplanned fails loudly.
const queue: Uint8Array[] = [];
const real = webcrypto.getRandomValues.bind(webcrypto);
Object.defineProperty(globalThis.crypto, 'getRandomValues', {
  configurable: true,
  value: <T extends ArrayBufferView | null>(target: T): T => {
    const next = queue.shift();
    if (!next) return real(target as never) as T;
    const view = new Uint8Array(target!.buffer, target!.byteOffset, target!.byteLength);
    if (next.length !== view.length)
      throw new Error(`Expected ${view.length} random bytes, queued ${next.length}`);
    view.set(next);
    return target;
  },
});
const plan = (...values: Uint8Array[]) => {
  queue.length = 0;
  queue.push(...values);
  return values.map(hex);
};
const done = () => {
  if (queue.length) throw new Error(`${queue.length} queued random values were not used`);
};
async function hkdf(secret: Uint8Array, info: string) {
  const base = await webcrypto.subtle.importKey('raw', secret, 'HKDF', false, ['deriveBits']);
  return new Uint8Array(
    await webcrypto.subtle.deriveBits(
      { name: 'HKDF', hash: 'SHA-256', salt: new Uint8Array(), info: new TextEncoder().encode(info) },
      base,
      256,
    ),
  );
}

// The same account as e2ee-vectors.ts.
const master = fixed('master', 32);
const keys = await accountKeys(master);
const secret = fixed('link-secret', 32);
const link = await linkKeys(secret);

const secretRandom = plan(fixed('link-secret-iv', 12));
const secretWrap = await wrapLinkSecret(keys, secret);
done();
if (hex(await unwrapLinkSecret(keys, secretWrap)) !== hex(secret)) throw new Error('secret round trip');
const serverUrl = 'https://harbor0content.online/s#AbCdEfGhIjKlMnOpQrStUv';

const names = [];
for (const [index, [itemId, name]] of [
  ['item-1', 'Holiday photos'],
  ['item-2', 'Café menu.pdf'],
  ['01J9ZK3', '日本語のファイル名.jpg'],
].entries()) {
  const random = plan(fixed(`link-name-iv-${index}`, 12));
  const nameWrap = await wrapLinkName(link, itemId, name);
  done();
  if ((await unwrapLinkName(link, itemId, nameWrap)) !== name.normalize('NFC'))
    throw new Error('name round trip');
  names.push({ itemId, name, random, nameWrap });
}

// A stored version's header, as FileCipher.create writes it, wrapped for the link; a visitor's cipher then
// decrypts the file the account sealed.
const fileRandom = plan(fixed('link-file-key', 32), fixed('link-file-prefix', 8), fixed('link-file-wrap', 12));
const cipher = await FileCipher.create(keys);
done();
const plain = new TextEncoder().encode('A file shared by an encrypted link.\n'.repeat(40));
const stored = await cipher.encryptedRange(plain.length, 0, encryptedSize(plain.length), async (a, b) =>
  plain.subarray(a, b),
);
const wrapRandom = plan(fixed('link-file-iv', 12));
const fileWrap = await wrapLinkFileKey(keys, link, cipher.header);
done();
const visitor = await openLinkFile(link, { keyWrap: fileWrap.keyWrap, head: fileWrap.head! });
const r = visitor.cipherRange(plain.length, 0, plain.length);
const opened = await visitor.decryptRange(plain.length, 0, plain.length, stored.subarray(r.start, r.end));
if (hex(opened) !== hex(plain)) throw new Error('visitor decrypt');

writeFileSync(
  out,
  JSON.stringify(
    {
      note: 'Generated by apps/android/e2ee-link-vectors.ts from packages/api-client/src/e2ee.ts. Do not edit.',
      master: hex(master),
      secret: hex(secret),
      linkKeys: {
        names: hex(await hkdf(secret, 'harbor0/e2ee/v1/link-names')),
        files: hex(await hkdf(secret, 'harbor0/e2ee/v1/link-files')),
      },
      secretWrap: { random: secretRandom, wrap: secretWrap },
      url: { server: serverUrl, shared: linkUrl(serverUrl, secret), secret: b64url(secret) },
      names,
      file: {
        random: fileRandom,
        header: hex(cipher.header),
        plain: hex(plain),
        stored: hex(stored),
        wrapRandom,
        keyWrap: fileWrap.keyWrap,
        head: fileWrap.head,
      },
    },
    null,
    2,
  ) + '\n',
);
console.log(`Wrote ${out}`);
process.exit(0);
